// errNoConfig is returned when there is no configuration and it cannot be asked for.
var errNoConfig = errors.New("you must supply at least OPENAI_API_KEY, AZURE_OPENAI_API_KEY, ANTHROPIC_API_KEY, or a config file path, " +
	"or run \"aigw run\" from a terminal to set up the providers interactively")

// savedConfigMarker identifies the configurations saved by the interactive setup. It is the first
// line of savedConfigHeader, and is looked for anywhere in the file so that it survives edits.
const savedConfigMarker = `# Agent Router configuration generated by the "aigw run" interactive setup.`

// savedConfigHeader is prepended to the configuration saved by the interactive setup.
const savedConfigHeader = savedConfigMarker + `
# It contains no API keys: they are read from the environment variables referenced
# as ${...} below, which must be set when running it.
#
# "aigw run" uses this file when it is at ~/.config/aigw/config.yaml. Edit it to change
# the routing rules (AIGatewayRoute) or providers, or delete it to run the setup again.
# See https://theagentrouter.ai/docs/cli/aigwrun for details.

`

// readConfig returns the configuration as a string from the given path,
// substituting environment variables. If OPENAI_API_KEY, AZURE_OPENAI_API_KEY or
// ANTHROPIC_API_KEY is set, it generates the config from environment variables. Otherwise, it runs the
// interactive setup, or returns an error if setup is nil.
func readConfig(path string, mcpServers *autoconfig.MCPServers, debug bool, setup *interactiveSetup) (string, error) {
	// If a file path is provided, prefer it.
	if path != "" {
		raw, err := os.ReadFile(path)
		if err != nil {
			return "", fmt.Errorf("error reading config: %w", err)
		}
		// Configurations saved by the interactive setup read the API keys from the environment:
		// fail clearly if they are missing, rather than sending unauthenticated requests.
		generated := strings.Contains(string(raw), savedConfigMarker)
		configBytes, err := envsubst.BytesRestricted(raw, generated, generated)
		if err != nil {
			if generated {
				return "", fmt.Errorf("%s reads the API keys from environment variables that are not set:\n%w\n"+
					"Export them in your shell (export <VARIABLE>=<API key>), or delete the file to run the interactive setup again", path, err)
			}
			return "", fmt.Errorf("error reading config: %w", err)
		}
		return string(configBytes), nil
	}

	var data autoconfig.ConfigData
	data.Debug = debug
	data.EnvoyVersion = os.Getenv("ENVOY_VERSION")

	// Add MCP servers if provided
	if mcpServers != nil {
		if err := autoconfig.AddMCPServers(&data, mcpServers); err != nil {
			return "", fmt.Errorf("failed to add MCP servers config: %w", err)
		}
	}

	// Add the providers configured in the environment. When both OpenAI and Anthropic are
	// configured, Claude models go to Anthropic and every other model to OpenAI.
	hasOpenAI := os.Getenv("OPENAI_API_KEY") != "" || os.Getenv("AZURE_OPENAI_API_KEY") != ""
	if os.Getenv("ANTHROPIC_API_KEY") != "" {
		models := autoconfig.AllModels
		if hasOpenAI {
			models = autoconfig.ClaudeModels
		}
		if err := autoconfig.PopulateAnthropicEnvConfig(&data, models); err != nil {
			return "", err
		}
	}
	if hasOpenAI {
		if err := autoconfig.PopulateOpenAIEnvConfig(&data, autoconfig.AllModels); err != nil {
			return "", err
		}
	}

	// If we've found no config data, ask the user for it if possible.
	if reflect.DeepEqual(data, autoconfig.ConfigData{Debug: debug, EnvoyVersion: os.Getenv("ENVOY_VERSION")}) {
		if setup == nil {
			return "", errNoConfig
		}
		if err := setup.prompt(&data); err != nil {
			return "", err
		}
	}

	// Otel access logging is handled by Envoy directly where supported.
	if err := autoconfig.PopulateOTELLogEnvConfig(&data); err != nil {
		return "", fmt.Errorf("failed to configure OTEL logging: %w", err)
	}

	// We have any auto-generated config: write it and apply envsubst
	config, err := autoconfig.WriteConfig(&data)
	if err != nil {
		return "", err
	}
	// Save the config before envsubst, as it is read back with envsubst applied.
	if setup != nil && setup.savePath != "" {
		if err = os.MkdirAll(filepath.Dir(setup.savePath), 0o750); err != nil {
			return "", fmt.Errorf("failed to create config directory: %w", err)
		}
		if err = os.WriteFile(setup.savePath, []byte(savedConfigHeader+config), 0o600); err != nil {
			return "", fmt.Errorf("failed to save config %s: %w", setup.savePath, err)
		}
	}
	return envsubst.String(config)
}

// expandPath expands environment variables and tilde in paths, then converts to absolute path.
// Returns empty string if input is empty.
// Replaces ~/  with ${HOME}/ before expanding environment variables.
func expandPath(path string) string {
	if path == "" {
		return ""
	}

	// Replace ~/ with ${HOME}/
	if strings.HasPrefix(path, "~/") {
		path = "${HOME}/" + path[2:]
	}

	// Expand environment variables
	expanded := os.ExpandEnv(path)

	// Convert to absolute path
	abs, err := filepath.Abs(expanded)
	if err != nil {
		// If we can't get absolute path, return expanded path
		return expanded
	}

	return abs
}
